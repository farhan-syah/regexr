#[test]
fn matches_the_unicode_grapheme_break_test_suite() {
    let re = regex(r"\X");
    let mut failures = Vec::new();

    for case in CASES {
        let text: String = case
            .iter()
            .flat_map(|cluster| cluster.iter())
            .map(|&cp| char::from_u32(cp).expect("test data holds scalar values"))
            .collect();

        let expected: Vec<String> = case
            .iter()
            .map(|cluster| {
                cluster
                    .iter()
                    .map(|&cp| char::from_u32(cp).unwrap())
                    .collect()
            })
            .collect();

        let got: Vec<String> = re
            .find_iter(&text)
            .map(|m| m.as_str().to_string())
            .collect();

        if got != expected {
            failures.push(format!(
                "  {:?}\n    expected {:?}\n    got      {:?}",
                describe(&text),
                expected.iter().map(|s| describe(s)).collect::<Vec<_>>(),
                got.iter().map(|s| describe(s)).collect::<Vec<_>>(),
            ));
        }
    }

    assert!(
        failures.is_empty(),
        "{} of {} grapheme-break cases failed:\n{}",
        failures.len(),
        CASES.len(),
        failures.join("\n")
    );
}

/// Codepoints of `s`, so a failure names characters that are invisible or
/// indistinguishable when printed.
fn describe(s: &str) -> String {
    s.chars()
        .map(|c| format!("U+{:04X}", c as u32))
        .collect::<Vec<_>>()
        .join(" ")
}
